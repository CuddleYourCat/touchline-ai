using Microsoft.AspNetCore.OpenApi;
using Microsoft.OpenApi;
using Touchline.Domain.Analytics;
using Touchline.Domain.Matches;
using Touchline.Domain.Squad;

namespace Touchline.MatchCentre.Api;

/// <summary>
/// Adds the live stream's message schemas to the OpenAPI document. OpenAPI can describe the
/// stream endpoint but not the messages inside it, so without this their types would be
/// missing from the document, and from the TypeScript generated from it (ADR-028).
/// </summary>
internal sealed class StreamMessageSchemas : IOpenApiDocumentTransformer
{
    /// <summary>The data type of every stream event, from <see cref="StreamEvents"/>.</summary>
    public static readonly IReadOnlyList<Type> Types =
    [
        typeof(LiveState),
        typeof(MatchEvent),
        typeof(MomentView),
        typeof(CommentaryLine),
        typeof(MomentAnalysis),
        typeof(MilestoneView),
        typeof(MomentumReading),
        typeof(OverlayCard),
        typeof(Heartbeat)
    ];

    /// <inheritdoc />
    public async Task TransformAsync(OpenApiDocument document, OpenApiDocumentTransformerContext context, CancellationToken cancellationToken)
    {
        document.Info.Title = "Touchline Match Centre API";
        document.Info.Description = "Live, explainable commentary for synthetic football matches. Every club, player and event is generated by a simulator.";

        foreach (var type in Types)
        {
            if (document.Components?.Schemas?.ContainsKey(type.Name) == true)
            {
                continue;
            }

            var schema = await context.GetOrCreateSchemaAsync(type, null, cancellationToken);
            document.AddComponent(type.Name, schema);
        }

        DescribeStreamBody(document);
    }

    // The generator describes the stream's body as the SseItem<object> type that produces it,
    // which isn't what goes over the wire. The body is text, and its messages are described
    // in the operation's description and the component schemas above.
    private static void DescribeStreamBody(OpenApiDocument document)
    {
        var stream = document.Paths?.Values
            .SelectMany(path => path.Operations is { } operations ? operations.Values : Enumerable.Empty<OpenApiOperation>())
            .FirstOrDefault(operation => operation.OperationId == "StreamMatch");
        if (stream?.Responses?.TryGetValue("200", out var ok) == true
            && ok.Content?.TryGetValue("text/event-stream", out var body) == true)
        {
            body.Schema = new OpenApiSchema
            {
                Type = JsonSchemaType.String,
                Description = "Server-sent event messages. See the operation description for each event's data schema."
            };
        }

        document.Components?.Schemas?.Remove("SseItemOfObject");
    }
}
